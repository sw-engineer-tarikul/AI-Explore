#!/usr/bin/env python3
"""
Create and link a GitHub draft pull request for a completed Fabro run.
Mints an installation token using the GitHub App private key in the Fabro database.
"""

import base64
import hashlib
import json
import os
import re
import sqlite3
import subprocess
import sys
import tempfile
import time
import urllib.error
import urllib.request

REPO = "sw-engineer-tarikul/AI-Explore"
APP_ID = "5700740"
INSTALLATION_ID = "180623836"


def mint_token():
    temp_dir = tempfile.gettempdir()
    db_path = os.path.join(temp_dir, "fabro-pr-mint.sqlite3")
    res = subprocess.run(
        ["docker", "cp", "fabro-server:/storage/db/fabro.sqlite3", db_path],
        capture_output=True,
    )
    if res.returncode != 0:
        raise RuntimeError(f"Failed to copy fabro database: {res.stderr.decode()}")

    con = sqlite3.connect(db_path)
    cur = con.cursor()
    cur.execute("SELECT value FROM secrets WHERE name='GITHUB_APP_PRIVATE_KEY'")
    row = cur.fetchone()
    con.close()
    try:
        os.remove(db_path)
    except OSError:
        pass

    if not row:
        raise RuntimeError("GITHUB_APP_PRIVATE_KEY not found in Fabro database.")

    raw_val = row[0]
    pem = raw_val if "-----BEGIN" in raw_val else base64.b64decode(raw_val).decode()
    m = re.search(
        r"-----BEGIN (?:RSA )?PRIVATE KEY-----(.*?)-----END (?:RSA )?PRIVATE KEY-----",
        pem,
        re.S,
    )
    if not m:
        raise RuntimeError("Failed to parse RSA private key from PEM.")

    body = base64.b64decode("".join(m.group(1).split()))

    def read_len(buf, i):
        b = buf[i]
        i += 1
        if b < 0x80:
            return b, i
        n = b & 0x7F
        return int.from_bytes(buf[i : i + n], "big"), i + n

    def parse(buf, i=0):
        tag = buf[i]
        i += 1
        ln, i = read_len(buf, i)
        return tag, buf[i : i + ln], i + ln

    _, seq, _ = parse(body)
    i = 0
    vals = []
    while i < len(seq):
        t, v, i = parse(seq, i)
        vals.append(v)
    n = int.from_bytes(vals[1], "big")
    d = int.from_bytes(vals[3], "big")
    k = (n.bit_length() + 7) // 8

    def b64u(b):
        return base64.urlsafe_b64encode(b).rstrip(b"=").decode()

    now = int(time.time())
    h = b64u(json.dumps({"alg": "RS256", "typ": "JWT"}, separators=(",", ":")).encode())
    p = b64u(
        json.dumps(
            {"iat": now - 60, "exp": now + 540, "iss": APP_ID}, separators=(",", ":")
        ).encode()
    )
    si = f"{h}.{p}".encode()
    di = (
        bytes.fromhex("3031300d060960864801650304020105000420")
        + hashlib.sha256(si).digest()
    )
    em = b"\x00\x01" + b"\xff" * (k - len(di) - 3) + b"\x00" + di
    jwt = f"{h}.{p}.{b64u(pow(int.from_bytes(em, 'big'), d, n).to_bytes(k, 'big'))}"

    req = urllib.request.Request(
        f"https://api.github.com/app/installations/{INSTALLATION_ID}/access_tokens",
        method="POST",
        headers={
            "Authorization": "Bearer " + jwt,
            "Accept": "application/vnd.github+json",
            "User-Agent": "fabro-pr-helper",
            "X-GitHub-Api-Version": "2022-11-28",
        },
        data=b"{}",
    )
    with urllib.request.urlopen(req, timeout=30) as r:
        return json.loads(r.read().decode())["token"]


def main():
    if len(sys.argv) < 2:
        print("Usage: make_pr.py <RUN_ID> [OPTIONAL_TITLE]")
        sys.exit(1)

    run_id = sys.argv[1]
    branch = f"fabro/run/{run_id}"

    token = mint_token()

    def gh_call(path, method="GET", payload=None):
        data = json.dumps(payload).encode() if payload is not None else None
        req = urllib.request.Request(
            "https://api.github.com" + path,
            data=data,
            method=method,
            headers={
                "Authorization": f"Bearer {token}",
                "Accept": "application/vnd.github+json",
                "User-Agent": "fabro-pr-helper",
                "Content-Type": "application/json",
            },
        )
        try:
            with urllib.request.urlopen(req, timeout=30) as r:
                return r.status, json.load(r)
        except urllib.error.HTTPError as e:
            return e.code, e.read().decode("utf-8", "replace")

    status, compare = gh_call(f"/repos/{REPO}/compare/main...{branch}")
    if status != 200:
        print(f"Error: comparing branch main...{branch} failed: {compare}")
        sys.exit(1)

    title = sys.argv[2] if len(sys.argv) > 2 else "Update Data Engine landing page"
    body = f"""## Summary

Static landing page update generated by Fabro workflow `web-page` (run `{run_id}`).

- `web/index.html`
- `web/styles.css`

## Verification
- Verified by structural automated checks
- Reviewed and confirmed by workflow agents
"""

    status, pr = gh_call(
        f"/repos/{REPO}/pulls",
        method="POST",
        payload={
            "title": title,
            "head": branch,
            "base": "main",
            "body": body,
            "draft": True,
        },
    )

    if status in (200, 201):
        pr_url = pr.get("html_url")
        print(f"Draft PR created: {pr_url}")
        # Link back into Fabro
        subprocess.run(
            ["docker", "exec", "fabro-server", "fabro", "pr", "link", run_id, pr_url],
            capture_output=True,
        )
        print(f"Linked pull request to run {run_id}.")
    else:
        print(f"PR creation returned status {status}: {pr}")


if __name__ == "__main__":
    main()
